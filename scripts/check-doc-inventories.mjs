import { access, readFile, readdir, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { fileURLToPath } from "node:url";

const root = fileURLToPath(new URL("../", import.meta.url));
const writeMode = process.argv.includes("--write");

function collectRuntimeExports(source) {
  const names = new Set(
    Array.from(
      source.matchAll(/export\s+(?:async\s+)?(?:function|class|const)\s+([A-Za-z_$][\w$]*)/gu),
      (match) => match[1],
    ),
  );

  for (const match of source.matchAll(
    /export\s*\{([\s\S]*?)\}(?:\s*from\s*["'][^"']+["'])?\s*;/gu,
  )) {
    const specifiers = match[1]
      .replaceAll(/\/\*[\s\S]*?\*\//gu, "")
      .replaceAll(/\/\/.*$/gmu, "")
      .split(",");
    for (const specifier of specifiers) {
      const normalized = specifier.trim();
      if (!normalized || normalized.startsWith("type ")) continue;
      const alias = normalized.match(/\bas\s+([A-Za-z_$][\w$]*)$/u);
      const direct = normalized.match(/^([A-Za-z_$][\w$]*)$/u);
      const exportedName = alias?.[1] ?? direct?.[1];
      if (exportedName) names.add(exportedName);
    }
  }

  return Array.from(names).sort();
}

const mcpSource = await readFile(join(root, "packages/mcp-server/src/index.ts"), "utf8");
const toolNames = Array.from(
  mcpSource.matchAll(/name:\s*"(vizcrush_[^"]+)"/gu),
  (match) => match[1],
).sort();

const packageEntries = [];
for (const entry of await readdir(join(root, "packages"), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  const packageJsonPath = join(root, "packages", entry.name, "package.json");
  const sourcePath = join(root, "packages", entry.name, "src/index.ts");
  try {
    const packageJson = JSON.parse(await readFile(packageJsonPath, "utf8"));
    const source = await readFile(sourcePath, "utf8");
    const runtimeExports = collectRuntimeExports(source);
    packageEntries.push({ name: packageJson.name, version: packageJson.version, runtimeExports });
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
packageEntries.sort((a, b) => a.name.localeCompare(b.name));

const runnableExamples = [];
for (const entry of await readdir(join(root, "examples"), { withFileTypes: true })) {
  if (!entry.isDirectory()) continue;
  try {
    await access(join(root, "examples", entry.name, "index.html"));
    runnableExamples.push(entry.name);
  } catch (error) {
    if (error.code !== "ENOENT") throw error;
  }
}
runnableExamples.sort();

const exampleCountClaims = [
  ["README.md", /\[(\d+) runnable examples\]/u],
  ["docs/reference/examples.md", /ships with (\d+) runnable example apps/u],
  ["docs/developer-guide/architecture.md", /(\d+) runnable example apps/u],
  ["docs/user-guide/getting-started.md", /(\d+) runnable demos/u],
];
for (const [relativePath, pattern] of exampleCountClaims) {
  const source = await readFile(join(root, relativePath), "utf8");
  const claimedCount = source.match(pattern)?.[1];
  if (!claimedCount || Number.parseInt(claimedCount, 10) !== runnableExamples.length) {
    throw new Error(
      `${relativePath} has a stale runnable-example count; expected ${runnableExamples.length}`,
    );
  }
}

function renderMarkdownTable(headers, rows) {
  const widths = headers.map((header, index) =>
    Math.max(header.length, ...rows.map((row) => row[index].length)),
  );
  const renderRow = (row) =>
    `| ${row.map((cell, index) => cell.padEnd(widths[index])).join(" | ")} |`;

  return [
    renderRow(headers),
    renderRow(widths.map((width) => "-".repeat(width))),
    ...rows.map(renderRow),
  ].join("\n");
}

const packageTable = renderMarkdownTable(
  ["Package", "Version", "Runtime exports"],
  packageEntries.map((entry) => [
    `\`${entry.name}\``,
    `\`${entry.version}\``,
    entry.runtimeExports.map((name) => `\`${name}\``).join(", ") || "—",
  ]),
);

const generated = `<!-- Generated by scripts/check-doc-inventories.mjs. Do not edit manually. -->

# Generated project inventory

## Published packages

${packageTable}

## MCP tools (${toolNames.length})

${toolNames.map((name) => `- \`${name}\``).join("\n")}

## Runnable examples (${runnableExamples.length})

${runnableExamples.map((name) => `- \`${name}\``).join("\n")}
`;

const inventoryPath = join(root, "docs/reference/generated-inventory.md");
if (writeMode) {
  await writeFile(inventoryPath, generated);
} else {
  let current = "";
  try {
    current = await readFile(inventoryPath, "utf8");
  } catch {}
  if (current !== generated) {
    throw new Error("generated project inventory is stale; run `pnpm docs:inventory:write`");
  }
}

const mcpGuide = await readFile(join(root, "docs/user-guide/mcp.md"), "utf8");
const toolsSection = mcpGuide.slice(
  mcpGuide.indexOf("## Available tools"),
  mcpGuide.indexOf("All tools have Zod-validated schemas"),
);
const documentedTools = Array.from(
  new Set(Array.from(toolsSection.matchAll(/`(vizcrush_[^`]+)`/gu), (match) => match[1])),
).sort();
if (JSON.stringify(documentedTools) !== JSON.stringify(toolNames)) {
  const missing = toolNames.filter((name) => !documentedTools.includes(name));
  const extra = documentedTools.filter((name) => !toolNames.includes(name));
  throw new Error(
    `MCP guide tool list is stale (missing: ${missing.join(", ") || "none"}; extra: ${extra.join(", ") || "none"})`,
  );
}

console.log(
  `verified ${packageEntries.length} packages, ${toolNames.length} MCP tools, and ${runnableExamples.length} runnable examples`,
);
